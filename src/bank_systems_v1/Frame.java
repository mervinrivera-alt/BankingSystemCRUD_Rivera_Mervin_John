private void closePanelAnimation(javax.swing.JPanel panel, java.awt.event.MouseEvent evt) {
    // 1. Safety Check: Did the mouse actually leave the panel's outer bounds?
    // (This stops it from closing if you hover over a button inside the panel)
    java.awt.Point p = evt.getPoint();
    if (p.x >= 0 && p.x < panel.getWidth() && p.y >= 0 && p.y < panel.getHeight()) {
        return; // Mouse is still safely inside, do nothing!
    }

    // 2. The Reverse Animation Timer
    javax.swing.Timer closeTimer = new javax.swing.Timer(33, new java.awt.event.ActionListener() {
        
        // Grab the panel's current size dynamically
        int currentWidth = panel.getWidth();
        int currentHeight = panel.getHeight();
        
        final int widthSpeed = 100; 
        final int heightSpeed = 140; 

        @Override
        public void actionPerformed(java.awt.event.ActionEvent e) {
            
            // Phase 1: Shrink the WIDTH first
            if (currentWidth > 0) {
                currentWidth -= widthSpeed;
                if (currentWidth < 0) currentWidth = 0; // Clamp to 0
            } 
            // Phase 2: Once width is 0, shrink the HEIGHT
            else if (currentHeight > 0) {
                currentHeight -= heightSpeed;
                if (currentHeight < 0) currentHeight = 0; // Clamp to 0
            } 
            // Phase 3: Animation is finished
            else {
                ((javax.swing.Timer) e.getSource()).stop();
                panel.setVisible(false); // Hide it
            }

            // Apply the shrinking bounds back to the specific panel
            panel.setBounds(0, 0, currentWidth, currentHeight);
            panel.revalidate();
            panel.repaint();
        }
    });
    
    closeTimer.start();
    jPanel20.setVisible(true);
    jPanel20.revalidate();
    jPanel20.repaint();
}
