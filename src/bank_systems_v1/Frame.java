    private void jButton6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton6ActionPerformed
        String searchKeyword = jTextField11.getText().trim();

    // Check if the search bar is empty
    if (searchKeyword.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter a name or Account ID to search.", "Input Required", JOptionPane.WARNING_MESSAGE);
        jTextField11.requestFocus();
        return;
    }

    // Get your pre-configured table model and clear existing records
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable2.getModel();
    model.setRowCount(0);

    // SQL query linking accounts and customers, filtering by ID, First Name, or Last Name
    String sql = "SELECT a.`Acount ID`, a.`Account Type`, a.`Balance`, c.`First Name`, c.`Last Name` " +
                 "FROM banking_system.`account table` a " +
                 "INNER JOIN banking_system.`customer table` c " +
                 "ON a.`Customer Table_Customer ID` = c.`Customer ID` " +
                 "WHERE a.`Acount ID` LIKE ? OR c.`First Name` LIKE ? OR c.`Last Name` LIKE ?";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement stmt = conn.prepareStatement(sql)) {
        
        // Using wildcards (%) so it matches partial text (e.g., "John" matches "Johnathan")
        String matchPattern = "%" + searchKeyword + "%";
        stmt.setString(1, matchPattern);
        stmt.setString(2, matchPattern);
        stmt.setString(3, matchPattern);

        try (ResultSet rs = stmt.executeQuery()) {
            boolean recordsFound = false;
            
            while (rs.next()) {
                recordsFound = true;
                Object[] rowData = {
                    rs.getInt("Acount ID"),
                    rs.getString("First Name"),
                    rs.getString("Last Name"),
                    rs.getString("Account Type"),
                    rs.getDouble("Balance")
                };
                model.addRow(rowData);
            }
            
            // If nothing matched, let the user know
            if (!recordsFound) {
                JOptionPane.showMessageDialog(this, "No matching accounts or customers found.", "Search Results", JOptionPane.INFORMATION_MESSAGE);
            }
        }
        
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Database Error during search: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton6ActionPerformed

    private void jPanel20MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jPanel20MouseClicked
       jPanel20.setVisible(false);
        jPanel19.setBounds(0, 0, 2, 0);
jPanel19.setVisible(true);

// 33ms delay gives roughly 30 FPS
javax.swing.Timer timer = new javax.swing.Timer(33, new java.awt.event.ActionListener() {
    
    // Track our current sizes (start width at 2 so we can see the line drop)
    int currentWidth = 2;
    int currentHeight = 0;
    
    // Set your final targets
    final int targetWidth = 270;
    final int targetHeight = 720;
    
    // Set the speed (pixels to add per frame)
    final int widthSpeed = 100; 
    final int heightSpeed = 140; 

    @Override
    public void actionPerformed(java.awt.event.ActionEvent e) {
        
        // Phase 1: Expand the HEIGHT first (from 0 to 720)
        if (currentHeight < targetHeight) {
            currentHeight += heightSpeed;
            
            // If we overshoot, clamp it perfectly to 720
            if (currentHeight > targetHeight) {
                currentHeight = targetHeight;
            }
        } 
        // Phase 2: Once height is done, expand the WIDTH (from 2 to 270)
        else if (currentWidth < targetWidth) {
            currentWidth += widthSpeed;
            
            // If we overshoot the target, clamp it perfectly to 270
            if (currentWidth > targetWidth) {
                currentWidth = targetWidth;
            }
        } 
        // Phase 3: Animation is completely finished
        else {
            // Stop the timer
            ((javax.swing.Timer) e.getSource()).stop();
        }

        // Apply the new bounds to the panel for this frame
        jPanel19.setBounds(0, 0, currentWidth, currentHeight);
        
        // Refresh the panel so the visual changes appear immediately
        jPanel19.revalidate();
        jPanel19.repaint();
    }
});
jPanel19.getParent().setComponentZOrder(jPanel19, 0);
jPanel19.getParent().repaint();
// Start the animation
timer.start();
    }//GEN-LAST:event_jPanel20MouseClicked

