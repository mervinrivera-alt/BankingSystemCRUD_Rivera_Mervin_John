    private void setupGlassPane() {
    // Create a custom Glass Pane that knows how to "punch holes" for your menus
    javax.swing.JPanel customGlassPane = new javax.swing.JPanel() {
        @Override
        public boolean contains(int x, int y) {
            // Check if jPanel12 is visible and the mouse is over it
            if (jPanel12.isVisible()) {
                java.awt.Point p = javax.swing.SwingUtilities.convertPoint(this, x, y, jPanel12);
                if (jPanel12.contains(p)) return false; // RETURN FALSE means "Let the click pass through perfectly"
            }
            // Check jPanel15
            if (jPanel15.isVisible()) {
                java.awt.Point p = javax.swing.SwingUtilities.convertPoint(this, x, y, jPanel15);
                if (jPanel15.contains(p)) return false; 
            }
            // Check jPanel17
            if (jPanel17.isVisible()) {
                java.awt.Point p = javax.swing.SwingUtilities.convertPoint(this, x, y, jPanel17);
                if (jPanel17.contains(p)) return false; 
            }
            
            // If the mouse is ANYWHERE ELSE, return true to block the click!
            return true; 
        }
    };

    customGlassPane.setOpaque(false); // Keep the shield invisible
    
    // Add a basic listener to catch the blocked clicks and beep
    customGlassPane.addMouseListener(new java.awt.event.MouseAdapter() {
        @Override
        public void mousePressed(java.awt.event.MouseEvent e) {
            java.awt.Toolkit.getDefaultToolkit().beep(); 
        }
    });

    // Apply this custom shield to your main window
    this.setGlassPane(customGlassPane);
}

