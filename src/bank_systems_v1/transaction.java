    private void jPanel10MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jPanel10MouseClicked
        jPanel9.setBounds(0, 0, 2, 0);
        jPanel9.setVisible(true);

        javax.swing.Timer timer = new javax.swing.Timer(33, new java.awt.event.ActionListener() {
            int currentWidth = 2;
            int currentHeight = 0;

            final int targetWidth = 270;
            final int targetHeight = 720;

            final int widthSpeed = 100;
            final int heightSpeed = 140;

            @Override
            public void actionPerformed(java.awt.event.ActionEvent e) {
                if (currentHeight < targetHeight) {
                    currentHeight += heightSpeed;
                    if (currentHeight > targetHeight) {
                        currentHeight = targetHeight;
                    }
                } else if (currentWidth < targetWidth) {
                    currentWidth += widthSpeed;
                    if (currentWidth > targetWidth) {
                        currentWidth = targetWidth;
                    }
                } else {
                    ((javax.swing.Timer) e.getSource()).stop();
                }

                jPanel9.setBounds(0, 0, currentWidth, currentHeight);
                jPanel9.revalidate();
                jPanel9.repaint();
            }
        });

        jPanel9.getParent().setComponentZOrder(jPanel9, 0);
        jPanel9.getParent().repaint();
        jPanel10.setVisible(false);
        timer.start();
    }//GEN-LAST:event_jPanel10MouseClicked

    private void jPanel9MouseExited(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jPanel9MouseExited
        java.awt.Point p = evt.getPoint();
        if (p.x >= 0 && p.x < jPanel9.getWidth() && p.y >= 0 && p.y < jPanel9.getHeight()) {
            return;
        }

        javax.swing.Timer closeTimer = new javax.swing.Timer(33, new java.awt.event.ActionListener() {

            int currentWidth = jPanel9.getWidth();
            int currentHeight = jPanel9.getHeight();

            final int widthSpeed = 100;
            final int heightSpeed = 140;

            @Override
            public void actionPerformed(java.awt.event.ActionEvent e) {

                if (currentWidth > 0) {
                    currentWidth -= widthSpeed;
                    if (currentWidth < 0) {
                        currentWidth = 0;
                    }
                } else if (currentHeight > 0) {
                    currentHeight -= heightSpeed;
                    if (currentHeight < 0) {
                        currentHeight = 0;
                    }
                } else {
                    ((javax.swing.Timer) e.getSource()).stop();
                    jPanel9.setVisible(false);
                }

                jPanel9.setBounds(0, 0, currentWidth, currentHeight);
                jPanel9.revalidate();
                jPanel9.repaint();
            }
        });

        closeTimer.start();
        jPanel10.setVisible(true);
        jPanel10.revalidate();
        jPanel10.repaint();
    }//GEN-LAST:event_jPanel9MouseExited

