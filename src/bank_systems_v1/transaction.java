    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if (jComboBox1.getSelectedIndex() <= 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select an account from the dropdown first.", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    String transType = jLabel4.getText().trim();
    if (!transType.equalsIgnoreCase("Deposit") && !transType.equalsIgnoreCase("Withdrawal")) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a transaction type (Deposit or Withdrawal) first.", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    String amountStr = jTextField4.getText().trim();
    if (amountStr.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter an amount.", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    double amount = 0.0;
    try {
        amount = Double.parseDouble(amountStr);
        if (amount <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Amount must be greater than zero. Negative numbers and zero are not allowed.", "Invalid Amount", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (amount > 999999.99) {
            javax.swing.JOptionPane.showMessageDialog(this, "Amount exceeds the maximum allowed system limit of 999,999.99.", "Limit Exceeded", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Invalid Amount. Please enter numbers only.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    int accountId = A.getID();

    if (transType.equalsIgnoreCase("Deposit")) {
        boolean success = B.deposit(accountId, amount);
        if (success) {
            jPanel6.setBackground(new Color(255,255,51));
            jLabel2.setForeground(new Color(0,0,51));
            jPanel7.setBackground(new Color(255,255,51));
            jLabel3.setForeground(new Color(0,0,51));
            javax.swing.JOptionPane.showMessageDialog(this, "Deposit Successful!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Database error processing deposit.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
    } else if (transType.equalsIgnoreCase("Withdrawal")) {
        int result = B.withdraw(accountId, amount);
        if (result == 1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Withdrawal Successful!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        } else if (result == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Insufficient balance available!", "Insufficient Funds", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Database error processing withdrawal.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
    }

    jTextField4.setText("");
    jLabel4.setText("");
    combobox();
    viewAllTransactions();
    }//GEN-LAST:event_jButton2ActionPerformed

